const fs = require("node:fs");
const path = require("node:path");

const skillRoot = "C:\\Users\\Administrator\\Desktop\\skill";
const appRoot = path.resolve(__dirname, "..");
const manifest = JSON.parse(fs.readFileSync(path.join(skillRoot, "manifest.json"), "utf8"));

function classify(item) {
  const role = String(item.role || "");
  const category = String(item.source_category || "");
  const name = String(item.name || "");
  const text = `${category} ${name}`;
  if (role === "编剧") return "writer";
  if (role === "分镜") return /运镜|摄影机|镜头运动|推拉摇移|轨道|航拍/.test(text) ? "prompt" : "storyboard";
  if (role === "视频") return /运镜|摄影机|镜头语言|提示词|推镜|拉镜|摇镜|移镜|环绕|跟拍/.test(text) ? "prompt" : "video";
  if (role === "剪辑") return /声音|音频|音效|配音|对白|音乐|混音|声画|降噪|拟音/.test(text) ? "voice" : "editor";
  if (role === "导演") {
    if (/GPT-Image|图片提示词|图像提示词|人像生成|产品渲染|艺术创作|概念设计|风格迁移/.test(text)) return "image";
    if (/角色塑造|面部|表情|姿态|服装|角色|妆容|发型|眼神|手部|年龄|职业形象|伤痕/.test(text)) return "character";
    if (/场景与环境|自然景观|城市街景|室内空间|水下|太空|废墟|天气|奇幻场景|季节|交通工具|宗教场所|军事场景|医疗场景|教育场景/.test(text)) return "scene";
    if (/构图|景别|轴线|机位|镜头调度/.test(text)) return "storyboard";
    return "director";
  }
  return "producer";
}

function extractSummary(content, fallback) {
  const match = content.replace(/\r/g, "").match(/##\s*用途\s*\n+([\s\S]*?)(?=\n##\s|\s*$)/);
  const text = String(match ? match[1] : fallback)
    .replace(/[#*`>\[\]]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return text.slice(0, 180) || fallback;
}

const items = manifest.items.map((item) => {
  const content = fs.readFileSync(path.join(skillRoot, item.relative_path), "utf8").replace(/^\uFEFF/, "").trim();
  const title = String(item.name || path.basename(item.relative_path, ".md")).trim();
  const summary = extractSummary(content, title);
  return {
    id: `builtin-library-${String(item.id).padStart(3, "0")}`,
    agentId: classify(item),
    title,
    name: title,
    summary,
    description: summary,
    content,
    tags: ["默认技能", String(item.role), String(item.source_category || "综合能力")],
    source: `34AI Skill Library / ${item.relative_path.replace(/\\/g, "/")}`,
    builtIn: true,
  };
});

